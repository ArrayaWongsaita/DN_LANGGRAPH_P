import { greet } from "./greet";

// ตัวตรวจของบทนี้ (ไม่ต้องแก้ไฟล์นี้)
test("greet ต้องทักทายด้วยคำว่า สวัสดี ตามด้วยชื่อ", () => {
  expect(greet("มาลี")).toBe("สวัสดี มาลี");
});

test("ใช้ได้กับชื่ออื่นด้วย (ห้าม hard-code ชื่อเดียว)", () => {
  expect(greet("สมชาย")).toBe("สวัสดี สมชาย");
});
