// แนวทาง: ให้ข้อความ error มีเลขครั้ง `fail ${calls}` แล้วคาดว่าได้ "fail 3" เมื่อ retries: 2
// ------------------------------------------------
test.todo("ลองครบแล้ว throw error ล่าสุด");
// 👉 เขียน test ของข้อ 2 ตรงนี้

